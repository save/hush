// Generates src/core/icons.js: the handful of Lucide icons the in-page palette
// uses, as plain data (no runtime dependency). Lucide is ISC-licensed.
// Run: node ui/gen-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const NAMES = [
  'house', 'compass', 'bell', 'message-circle', 'bookmark', 'user', 'list', 'settings', 'pencil', 'search',
  'rotate-cw', 'keyboard', 'heart', 'history', 'clock', 'thumbs-up', 'list-video', 'circle-user', 'power',
  'wind', 'droplet', 'sliders-horizontal', 'eye-off', 'panel-left', 'focus', 'shopping-bag', 'chart-column',
  'users', 'shirt', 'package', 'repeat', 'globe', 'image', 'message-square-off', 'arrow-right', 'sparkles',
  'eye', 'undo-2', 'mouse-pointer-click', 'palette',
];
const dir = path.resolve('node_modules/lucide-react/dist/esm/icons');
const out = {};
for (const name of NAMES) {
  const src = fs.readFileSync(path.join(dir, `${name}.js`), 'utf8');
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  if (!m) throw new Error(`no icon node in ${name}`);
  const node = Function(`return ${m[1]}`)();
  out[name] = node.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
}
const body = `// hush — Lucide icons (https://lucide.dev, ISC license) used by the palette.
// Generated by ui/gen-icons.mjs — do not edit by hand.
(() => {
  const H = globalThis.Hush;
  if (!H || H.icons) return;
  H.icons = ${JSON.stringify(out)};
})();
`;
fs.writeFileSync(path.resolve('src/core/icons.js'), body);
console.log(`wrote ${NAMES.length} icons, ${body.length} bytes`);
